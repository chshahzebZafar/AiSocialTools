export function getDirectoryToolBySlug(slug: string): AIDirectoryTool | undefined {
  return aiDirectoryTools.find((t) => t.slug === slug && t.approved);
}

export function getApprovedDirectoryTools(): AIDirectoryTool[] {
  return aiDirectoryTools.filter((t) => t.approved);
}

export function getFeaturedDirectoryTools(): AIDirectoryTool[] {
  return aiDirectoryTools.filter((t) => t.approved && t.featured);
}

export function getTrendingDirectoryTools(): AIDirectoryTool[] {
  return aiDirectoryTools.filter((t) => t.approved && t.trending);
}

export function getDirectoryToolsByCategory(category: AICategory): AIDirectoryTool[] {
  return aiDirectoryTools.filter(
    (t) =>
      t.approved &&
      (t.category === category || t.subcategories?.includes(category))
  );
}
