/**
 * AI Directory — external AI tools listed in our community directory.
 * Different from `socialTools` (which are our own first-party tools).
 *
 * Adding a tool:
 *   1. Append a new entry to `aiDirectoryTools` below.
 *   2. Make sure `slug` is unique and URL-safe.
 *   3. Optional: set `featured: true` to put it in the homepage strip.
 *   4. Rebuild + redeploy.
 */

export type AIPricing = "Free" | "Freemium" | "Paid" | "Open Source";

export interface AIDirectoryTool {
  /** unique kebab-case identifier — also used as URL slug */
  slug: string;
  /** display name */
  name: string;
  /** one-line pitch (max ~100 chars) */
  tagline: string;
  /** longer description; supports line breaks */
  description: string;
  /** external URL (the tool's homepage) */
  url: string;
  /** primary category, used for filtering */
  category: AICategory;
  /** secondary categories for cross-listing */
  subcategories?: AICategory[];
  /** pricing model */
  pricing: AIPricing;
  /** human-readable pricing detail (e.g. "Free up to 50 generations/day, then $20/mo") */
  pricingDetails?: string;
  /** key features list */
  features: string[];
  /** what it's good at */
  pros?: string[];
  /** known limitations */
  cons?: string[];
  /** related tool slugs (for "alternatives" section) */
  alternatives?: string[];
  /** lightweight tag list for search */
  tags?: string[];
  /** show on homepage / featured strip */
  featured?: boolean;
  /** trending in last 30 days */
  trending?: boolean;
  /** isNew if added < 30 days ago */
  isNew?: boolean;
  /** ISO date when added to directory */
  addedAt: string;
  /** ISO date when tool was first launched (optional) */
  launchedAt?: string;
  /** Twitter / X handle (without the @) */
  twitter?: string;
  /** company / founder name */
  founder?: string;
  /** logo URL — fallback to first letter of name */
  logoUrl?: string;
  /** for community submissions — name of submitter */
  submittedBy?: string;
  /** moderation flag — only true entries render */
  approved: boolean;
  /** tool is coming soon — show badge, disable external link */
  comingSoon?: boolean;
}

